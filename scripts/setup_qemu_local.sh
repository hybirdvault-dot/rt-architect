#!/usr/bin/env bash
#
# Install QEMU locally, without root.
#
# Deepin/UOS does not grant passwordless sudo, and QEMU is only available as
# .deb packages.  This downloads the packages and extracts them into a private
# prefix, then writes a wrapper that sets LD_LIBRARY_PATH.
#
# Usage:  bash scripts/setup_qemu_local.sh [prefix]
#         default prefix: ~/rt-architect-tools/qemu
#
# After it finishes, use:
#   ~/rt-architect-tools/qemu/bin/qemu-system-x86_64 --version

set -euo pipefail

PREFIX="${1:-$HOME/rt-architect-tools/qemu}"
DEB_DIR="$PREFIX/debs"

# qemu-system-x86 plus every runtime library the binary needs on this distro.
PACKAGES=(
    qemu-system-x86
    libcapstone5
    libfdt1
    libpmem1
    librdmacm1
    libibverbs1
    libvdeplug2
    libglib2.0-0
    libpixman-1-0
    libndctl6
    libdaxctl1
)

mkdir -p "$DEB_DIR" "$PREFIX/bin"
cd "$DEB_DIR"

echo "Downloading QEMU packages into $DEB_DIR ..."
for pkg in "${PACKAGES[@]}"; do
    if apt-get download "$pkg" >/dev/null 2>&1; then
        echo "  ok   $pkg"
    else
        echo "  MISS $pkg" >&2
    fi
done

echo "Extracting into $PREFIX ..."
for deb in ./*.deb; do
    [ -f "$deb" ] || continue
    dpkg-deb -x "$deb" "$PREFIX"
done

LIB_DIR="$PREFIX/usr/lib/x86_64-linux-gnu"
QEMU_REAL="$PREFIX/usr/bin/qemu-system-x86_64"

if [ ! -x "$QEMU_REAL" ]; then
    echo "ERROR: $QEMU_REAL not found after extraction" >&2
    exit 1
fi

cat > "$PREFIX/bin/qemu-system-x86_64" <<EOF
#!/bin/sh
# Generated by scripts/setup_qemu_local.sh — do not edit.
export LD_LIBRARY_PATH="$LIB_DIR:\${LD_LIBRARY_PATH:-}"
exec "$QEMU_REAL" "\$@"
EOF
chmod +x "$PREFIX/bin/qemu-system-x86_64"

echo
echo "QEMU installed at $PREFIX"
"$PREFIX/bin/qemu-system-x86_64" --version | head -1
