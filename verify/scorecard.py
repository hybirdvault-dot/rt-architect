"""Write the human-readable scorecard."""

import os

from verify.models import Scorecard

_HEADER = """# RTArchitect Verification Scorecard

Generated by `python verify/run_verify.py`. Exit codes: 0 = GREEN, 1 = YELLOW, 2 = RED.

| Layer | Check | Verdict | Severity | Evidence |
|---|---|---|---|---|
"""


def write(scorecard: Scorecard, path: str) -> str:
    counts = scorecard.counts()
    lines = [_HEADER]
    for r in sorted(scorecard.results, key=lambda x: (x.layer, x.name)):
        evidence = r.evidence.replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {r.layer} | {r.name} | {r.verdict} | {r.severity} | {evidence} |")
    summary = (
        f"\n## Summary\n\n- Checks run: {len(scorecard.results)}\n"
        f"- PASS: {counts.get('PASS', 0)}  FAIL: {counts.get('FAIL', 0)}  "
        f"WARN: {counts.get('WARN', 0)}  SKIP: {counts.get('SKIP', 0)}\n"
        f"- Exit code: {scorecard.exit_code()} "
        f"({'GREEN' if scorecard.exit_code() == 0 else 'YELLOW' if scorecard.exit_code() == 1 else 'RED'})\n"
    )
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n" + summary)
    return path
